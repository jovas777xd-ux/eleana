-- ELEANA: crear recursos propios DENTRO del proyecto Supabase de ALEXVAL.
-- Ejecutar una vez en SQL Editor del proyecto ALEXVAL.
-- No modifica las tablas public.productos o public.administradores de ALEXVAL.
-- No asigna permisos a ninguna cuenta de ALEXVAL.

create table public.eleana_administradores (
  usuario_id uuid primary key references auth.users(id) on delete cascade
);

create table public.eleana_productos (
  id bigint generated by default as identity primary key,
  codigo text unique,
  nombre text not null check (length(btrim(nombre)) > 0),
  descripcion text,
  categoria text not null default 'general',
  precio numeric(12,2) check (precio is null or precio >= 0),
  imagen text,
  video text,
  activo boolean not null default false,
  creado_en timestamptz not null default now()
);

alter table public.eleana_administradores enable row level security;
alter table public.eleana_productos enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.eleana_administradores to authenticated;
grant select on public.eleana_productos to anon, authenticated;
grant insert, update, delete on public.eleana_productos to authenticated;

create policy "ELEANA consultar mi permiso"
on public.eleana_administradores for select to authenticated
using (usuario_id = (select auth.uid()));

create policy "ELEANA publico ve activos"
on public.eleana_productos for select to anon, authenticated
using (activo = true);

create policy "ELEANA admin ve todos"
on public.eleana_productos for select to authenticated
using (
  exists (select 1 from public.eleana_administradores ea
          where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin agrega"
on public.eleana_productos for insert to authenticated
with check (
  exists (select 1 from public.eleana_administradores ea
          where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin edita"
on public.eleana_productos for update to authenticated
using (
  exists (select 1 from public.eleana_administradores ea
          where ea.usuario_id = (select auth.uid()))
)
with check (
  exists (select 1 from public.eleana_administradores ea
          where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin elimina ocultos"
on public.eleana_productos for delete to authenticated
using (
  activo = false
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
);

-- Bucket diferente al bucket 'productos' de ALEXVAL.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('eleana-productos', 'eleana-productos', true, 5242880,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

create policy "ELEANA admin lee archivos"
on storage.objects for select to authenticated
using (
  bucket_id = 'eleana-productos'
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin sube archivos"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'eleana-productos'
  and name like 'catalogo/%'
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin edita archivos"
on storage.objects for update to authenticated
using (
  bucket_id = 'eleana-productos'
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
)
with check (
  bucket_id = 'eleana-productos'
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
);

create policy "ELEANA admin elimina archivos"
on storage.objects for delete to authenticated
using (
  bucket_id = 'eleana-productos'
  and exists (select 1 from public.eleana_administradores ea
              where ea.usuario_id = (select auth.uid()))
);

-- Comprobar el RLS de las tablas nuevas.
select schemaname, tablename, rowsecurity
from pg_tables
where schemaname = 'public'
  and tablename in ('eleana_productos', 'eleana_administradores')
order by tablename;

